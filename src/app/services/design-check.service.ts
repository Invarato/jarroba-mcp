import { Injectable } from "@angular/core";
import { SchemaModel, TableModel, ColumnModel } from "./schema-introspect.service";
export type IssueLevel = "warn" | "info";
export type IssueCode = "no-pk" | "fk-no-index" | "float-money" | "timestamp-no-tz" | "dup-index" | "fk-type-mismatch" | "sequence-behind" | "serial-legacy" | "cascade-cycle";
export interface DesignIssue {
    level: IssueLevel;
    table: string;
    code: IssueCode;
    args: Record<string, string>;
    text: string;
    ddl?: string;
}
const RE_DINERO = /(price|amount|cost|salary|total|balance|fee|tax|precio|importe|coste|salario|saldo|monto|tarifa|impuesto)/i;
const RE_FLOAT = /^(real|double precision|float|float4|float8)$/i;
@Injectable({ providedIn: "root" })
export class DesignCheckService {
    check(schema: SchemaModel): DesignIssue[] {
        const issues: DesignIssue[] = [];
        const porId = new Map(schema.tables.map(t => [t.id, t]));
        for (const t of schema.tables) {
            if (t.isView)
                continue;
            const q = this.qualified(t);
            if (t.primaryKey.length === 0) {
                issues.push({
                    level: "warn",
                    table: t.id,
                    code: "no-pk",
                    args: { table: t.name },
                    text: `«${t.name}» no tiene clave primaria: no podrás editar filas de forma fiable.`,
                });
            }
            for (const fk of t.foreignKeys) {
                if (!(t.indexes ?? []).some(ix => this.startsWith(ix.columns, fk.columns))) {
                    issues.push({
                        level: "warn",
                        table: t.id,
                        code: "fk-no-index",
                        args: { table: t.name, columns: fk.columns.join(", ") },
                        text: `FK «${t.name}(${fk.columns.join(", ")})» sin índice: ralentiza joins y borrados en cascada.`,
                        ddl: `CREATE INDEX ON ${q} (${fk.columns.map(c => this.ident(c)).join(", ")});`,
                    });
                }
                const padre = porId.get(`${fk.refSchema}.${fk.refTable}`);
                if (padre) {
                    fk.columns.forEach((c, i) => {
                        const hija = t.columns.find(x => x.name === c);
                        const madre = padre.columns.find(x => x.name === fk.refColumns[i]);
                        if (hija && madre && !this.mismoTipo(hija, madre)) {
                            issues.push({
                                level: "warn",
                                table: t.id,
                                code: "fk-type-mismatch",
                                args: { table: t.name, column: c, type: hija.type, refTable: padre.name, refColumn: madre.name, refType: madre.type },
                                text: `«${t.name}.${c}» es ${hija.type} pero apunta a «${padre.name}.${madre.name}», que es ${madre.type}: la comparación no puede usar el índice.`,
                                ddl: `ALTER TABLE ${q} ALTER COLUMN ${this.ident(c)} TYPE ${this.baseType(madre.type)};`,
                            });
                        }
                    });
                }
            }
            for (const c of t.columns) {
                if (RE_DINERO.test(c.name) && RE_FLOAT.test(this.baseType(c.type))) {
                    issues.push({
                        level: "warn",
                        table: t.id,
                        code: "float-money",
                        args: { table: t.name, column: c.name, type: c.type },
                        text: `«${t.name}.${c.name}» guarda dinero en ${c.type} (coma flotante): usa numeric o perderás céntimos.`,
                        ddl: `ALTER TABLE ${q} ALTER COLUMN ${this.ident(c.name)} TYPE numeric(12,2);`,
                    });
                }
                if (/^timestamp( without time zone)?$/i.test(this.baseType(c.type))) {
                    issues.push({
                        level: "info",
                        table: t.id,
                        code: "timestamp-no-tz",
                        args: { table: t.name, column: c.name },
                        text: `«${t.name}.${c.name}» es timestamp sin zona horaria: considera timestamptz.`,
                        ddl: `ALTER TABLE ${q} ALTER COLUMN ${this.ident(c.name)} TYPE timestamptz;`,
                    });
                }
                if (/nextval\(/i.test(c.default ?? "")) {
                    issues.push({
                        level: "info",
                        table: t.id,
                        code: "serial-legacy",
                        args: { table: t.name, column: c.name },
                        text: `«${t.name}.${c.name}» usa serial: la forma estándar hoy es GENERATED BY DEFAULT AS IDENTITY.`,
                    });
                }
            }
            const idx = (t.indexes ?? []).filter(i => !i.primary && i.columns.length && !i.unique && !i.partial);
            const todos = (t.indexes ?? []).filter(i => i.columns.length);
            for (const a of idx) {
                const cubierto = todos.find(b => b.name !== a.name && b.columns.length >= a.columns.length
                    && this.startsWith(b.columns, a.columns)
                    && (b.columns.length > a.columns.length || a.name > b.name));
                if (cubierto) {
                    issues.push({
                        level: "info",
                        table: t.id,
                        code: "dup-index",
                        args: { table: t.name, index: a.name, columns: a.columns.join(", "), other: cubierto.name },
                        text: `El índice «${a.name}» (${a.columns.join(", ")}) ya está cubierto por «${cubierto.name}»: sobra y encarece las escrituras.`,
                        ddl: `DROP INDEX ${t.schema === "public" ? this.ident(a.name) : `${this.ident(t.schema)}.${this.ident(a.name)}`};`,
                    });
                }
            }
        }
        return issues;
    }
    private mismoTipo(a: ColumnModel, b: ColumnModel): boolean {
        const norm = (c: ColumnModel) => {
            const t = this.baseType(c.type);
            if (/^(serial|serial4|int4)$/.test(t))
                return "integer";
            if (/^(bigserial|serial8|int8)$/.test(t))
                return "bigint";
            if (/^int2$/.test(t))
                return "smallint";
            if (/^(varchar|character varying|char|character|bpchar|text)$/.test(t))
                return "texto";
            return t;
        };
        return norm(a) === norm(b);
    }
    private baseType(type: string): string {
        return (type ?? "").replace(/\(.*$/, "").trim().toLowerCase();
    }
    private startsWith(arr: string[], prefix: string[]): boolean {
        if (prefix.length > arr.length)
            return false;
        return prefix.every((p, i) => arr[i] === p);
    }
    private qualified(t: TableModel): string {
        return t.schema === "public" ? this.ident(t.name) : `${this.ident(t.schema)}.${this.ident(t.name)}`;
    }
    private ident(name: string): string { return "\"" + name.replace(/"/g, "\"\"") + "\""; }
}
