import { Injectable } from "@angular/core";
export type SourceDialect = "postgres" | "mysql" | "sqlite" | "mssql" | "oracle";
export interface SqlStatement {
    sql: string;
    start: number;
    line: number;
}
export interface DialectChange {
    ruleId: string;
    line: number;
    from: string;
    to: string;
}
export interface DetectResult {
    dialect: SourceDialect;
    markers: string[];
}
export interface TranslateResult {
    sql: string;
    changes: DialectChange[];
    dialect: SourceDialect;
}
interface Rule {
    id: string;
    re: RegExp;
    to: string | ((m: RegExpExecArray) => string);
}
