import { Injectable } from "@angular/core";
import { SchemaModel, TableModel, ColumnModel } from "./schema-introspect.service";
import { rnd, pad2, slug, pick, fullName, phoneEs, FIRST_NAMES, LAST_NAMES, CITIES, COUNTRIES, STREETS, COMPANIES, COLOR_NAMES, STATUSES, JOB_TITLES, WORDS, LOREM_SENTENCES, } from "../shared/fake-data";
export interface SampleDataOptions {
    rowsPerTable: number;
    onlyTables?: string[];
}
@Injectable({ providedIn: "root" })
export class SampleDataService {
    generate(schema: SchemaModel, opts: SampleDataOptions): string {
        const n = Math.max(1, Math.min(1000, opts.rowsPerTable || 10));
        const only = new Set(opts.onlyTables ?? []);
        const wanted = schema.tables.filter(t => !t.isView && (only.size === 0 || only.has(t.id)));
        const ordered = this.topoSort(wanted, schema);
        const blocks: string[] = [];
        for (const t of ordered) {
            const cols = t.columns.filter(c => !this.isAutoGenerated(c));
            if (cols.length === 0)
                continue;
            const enlace = this.bloqueDeEnlace(t, cols, n);
            if (enlace) {
                blocks.push(enlace);
                continue;
            }
            const colList = cols.map(c => this.ident(c.name)).join(", ");
            const rows: string[] = [];
            for (let i = 0; i < n; i++) {
                rows.push("(" + cols.map(c => this.valueFor(c, t, i)).join(", ") + ")");
            }
            blocks.push(`INSERT INTO ${this.qualified(t)} (${colList}) VALUES\n  ${rows.join(",\n  ")};`);
        }
        return blocks.join("\n\n");
    }
    private topoSort(tables: TableModel[], schema: SchemaModel): TableModel[] {
        const inSet = new Set(tables.map(t => t.id));
        const byId = new Map(tables.map(t => [t.id, t]));
        const deps = new Map<string, Set<string>>();
        for (const t of tables) {
            const d = new Set<string>();
            for (const fk of t.foreignKeys) {
                const parent = `${fk.refSchema}.${fk.refTable}`;
                if (parent !== t.id && inSet.has(parent))
                    d.add(parent);
            }
            deps.set(t.id, d);
        }
        const out: TableModel[] = [];
        const done = new Set<string>();
        let progress = true;
        while (out.length < tables.length && progress) {
            progress = false;
            for (const t of tables) {
                if (done.has(t.id))
                    continue;
                if ([...deps.get(t.id)!].every(d => done.has(d))) {
                    out.push(t);
                    done.add(t.id);
                    progress = true;
                }
            }
        }
        for (const t of tables)
            if (!done.has(t.id))
                out.push(t);
        void byId;
        return out;
    }
    private valueFor(c: ColumnModel, t: TableModel, i: number): string {
        if (c.isFk) {
            const sub = this.fkSubquery(c, t);
            if (sub)
                return sub;
        }
        const base = this.baseType(c.type);
        const name = c.name.toLowerCase();
        const uniqueish = c.isPk || this.looksUnique(c.name);
        const permitidos = this.valoresPermitidos(c.name, t);
        if (permitidos.length)
            return this.lit(permitidos[i % permitidos.length]);
        if (/^bool/.test(base))
            return this.boolByName(name);
        if (/^date$/.test(base) && /(nacim|birth|nacid|fecha_nac|dob)/.test(name)) {
            return `current_date - ${(18 + rnd(63)) * 365 + rnd(365)}`;
        }
        if (/^date$/.test(base))
            return `current_date - ${rnd(365)}`;
        if (/^(timestamp|timestamptz)/.test(base))
            return `now() - (${rnd(365)} || ' days')::interval`;
        if (/^time/.test(base))
            return this.lit(`${pad2(rnd(24))}:${pad2(rnd(60))}:00`);
        if (/^uuid$/.test(base))
            return "gen_random_uuid()";
        if (/^(json|jsonb)$/.test(base))
            return this.lit(`{"k": ${i}}`) + "::" + base;
        const isInt = /^(smallint|integer|bigint|int2|int4|int8)$/.test(base);
        const isNum = isInt || /^(numeric|decimal|real|double precision|float4|float8|money)$/.test(base);
        if (isNum)
            return this.numberByName(name, isInt, i, uniqueish);
        return this.lit(this.textByName(name, i, uniqueish));
    }
    private textByName(name: string, i: number, uniqueish: boolean): string {
        const uniq = (s: string) => uniqueish ? `${s} ${i + 1}` : s;
        if (/mail|correo/.test(name))
            return `${slug(pick(FIRST_NAMES))}${i + 1}@example.com`;
        if (/(first_?name|firstname|nombre_pila)/.test(name))
            return uniq(pick(FIRST_NAMES));
        if (/(last_?name|surname|apellido)/.test(name))
            return uniq(pick(LAST_NAMES));
        if (/(user_?name|usuario|login|nick)/.test(name))
            return `${slug(pick(FIRST_NAMES))}${slug(pick(LAST_NAMES))}${i + 1}`;
        if (/(full_?name|nombre|\bname\b|titular)/.test(name))
            return uniqueish ? `${fullName()} ${i + 1}` : fullName();
        if (/(city|ciudad|localidad|municipio)/.test(name))
            return pick(CITIES);
        if (/(country|pais|nacionalidad)/.test(name))
            return pick(COUNTRIES);
        if (/(address|direccion|calle|street|domicilio)/.test(name))
            return `${pick(STREETS)} ${1 + rnd(200)}`;
        if (/(company|empresa|organiz|compania)/.test(name))
            return pick(COMPANIES);
        if (/(phone|telefono|movil|celular|\btel\b)/.test(name))
            return phoneEs();
        if (/(url|website|\bweb\b|enlace|link)/.test(name))
            return `https://${slug(pick(COMPANIES))}.example.com`;
        if (/(colou?r|color)/.test(name))
            return pick(COLOR_NAMES);
        if (/(status|estado|state)/.test(name))
            return pick(STATUSES);
        if (/(descrip|notes|notas|comment|coment|bio|resumen|summary)/.test(name))
            return pick(LOREM_SENTENCES);
        if (/(title|titulo|puesto|cargo|\brole\b|\brol\b)/.test(name))
            return pick(JOB_TITLES);
        if (/(code|codigo|sku|\bref\b)/.test(name))
            return `${pick(WORDS).slice(0, 3).toUpperCase()}-${1000 + rnd(9000)}`;
        return uniqueish ? `${pick(WORDS)} ${i + 1}` : pick(WORDS);
    }
    private numberByName(name: string, isInt: boolean, i: number, uniqueish: boolean): string {
        if (uniqueish)
            return String(i + 1);
        let n: number;
        if (/(price|precio|amount|importe|cost|coste|salary|salario|total|monto|saldo|balance)/.test(name))
            n = 1 + Math.random() * 9999;
        else if (/(age|edad)/.test(name))
            n = 18 + rnd(63);
        else if (/(year|anio|\bano\b)/.test(name))
            n = 2000 + rnd(26);
        else if (/(qty|quantity|cantidad|stock|count|unidades)/.test(name))
            n = 1 + rnd(100);
        else if (/(rating|rank|score|puntuac|estrella|valorac)/.test(name))
            n = 1 + rnd(5);
        else if (/(percent|porcentaje|\bpct\b|ratio)/.test(name))
            n = Math.random() * 100;
        else
            n = isInt ? 1 + rnd(1000) : Math.random() * 1000;
        return isInt ? String(Math.round(n)) : n.toFixed(2);
    }
    private boolByName(name: string): string {
        const bias = /(activ|enabled|habilit|is_|visible|public|verificad|confirm)/.test(name) ? 0.75 : 0.5;
        return Math.random() < bias ? "true" : "false";
    }
    private fkSubquery(c: ColumnModel, t: TableModel): string | null {
        const fk = t.foreignKeys.find(f => f.columns.includes(c.name));
        if (!fk)
            return null;
        const k = fk.columns.indexOf(c.name);
        const refCol = fk.refColumns[k];
        const refTable = fk.refSchema === "public" ? this.ident(fk.refTable) : `${this.ident(fk.refSchema)}.${this.ident(fk.refTable)}`;
        return `(SELECT ${this.ident(refCol)} FROM ${refTable} ORDER BY random() LIMIT 1)`;
    }
    private bloqueDeEnlace(t: TableModel, cols: ColumnModel[], n: number): string | null {
        const pk = t.primaryKey ?? [];
        if (pk.length < 2)
            return null;
        const fks = pk.map(nombre => ({
            nombre,
            fk: t.foreignKeys.find(f => f.columns.includes(nombre)),
        }));
        if (fks.some(x => !x.fk))
            return null;
        const padres = fks.map((x, idx) => {
            const fk = x.fk!;
            const refCol = fk.refColumns[fk.columns.indexOf(x.nombre)];
            const tabla = fk.refSchema === "public" ? this.ident(fk.refTable) : `${this.ident(fk.refSchema)}.${this.ident(fk.refTable)}`;
            return { alias: `p${idx}`, expr: `${this.ident(refCol)}`, tabla, columna: x.nombre };
        });
        const seleccion = cols.map(c => {
            const padre = padres.find(p => p.columna === c.name);
            if (padre)
                return `${padre.alias}.${padre.expr}`;
            return `${this.expresionSql(c)} AS ${this.ident(c.name)}`;
        });
        const from = padres.map(p => `${p.tabla} ${p.alias}`).join(", ");
        return `INSERT INTO ${this.qualified(t)} (${cols.map(c => this.ident(c.name)).join(", ")})\n`
            + `SELECT ${seleccion.join(", ")}\n  FROM ${from}\n ORDER BY random() LIMIT ${n};`;
    }
    private expresionSql(c: ColumnModel): string {
        const base = this.baseType(c.type);
        const name = c.name.toLowerCase();
        if (/^bool/.test(base))
            return "random() < 0.5";
        if (/^date$/.test(base))
            return `current_date - (random() * 365)::int`;
        if (/^(timestamp|timestamptz)/.test(base))
            return `now() - (random() * 365 || ' days')::interval`;
        if (/^uuid$/.test(base))
            return "gen_random_uuid()";
        if (/^(json|jsonb)$/.test(base))
            return `'{}'::${base}`;
        if (/^(smallint|integer|bigint|int2|int4|int8)$/.test(base)) {
            return /(cantidad|qty|quantity|unidades|stock)/.test(name) ? "(1 + random() * 9)::int" : "(random() * 100)::int";
        }
        if (/^(numeric|decimal|real|double precision|float4|float8|money)$/.test(base)) {
            return "round((random() * 500 + 1)::numeric, 2)";
        }
        return this.lit(pick(WORDS));
    }
    private isAutoGenerated(c: ColumnModel): boolean {
        if (c.identity === "a" || c.identity === "d")
            return true;
        return !!c.default && /nextval\(/i.test(c.default);
    }
    private valoresPermitidos(columna: string, t: TableModel): string[] {
        for (const chk of t.checks ?? []) {
            const def = chk.def;
            if (!new RegExp(`\\b${columna.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`).test(def))
                continue;
            const arr = /ARRAY\[([^\]]*)\]/i.exec(def);
            if (!arr)
                continue;
            const vals = [...arr[1].matchAll(/'((?:[^']|'')*)'/g)].map(m => m[1].replace(/''/g, "'"));
            if (vals.length)
                return vals;
        }
        return [];
    }
    private looksUnique(name: string): boolean {
        return /(^|_)(email|username|slug|code|sku|name)$/i.test(name);
    }
    private baseType(type: string): string {
        return type.replace(/\(.*$/, "").replace(/\[\]$/, "").trim().toLowerCase();
    }
    private qualified(t: TableModel): string {
        return t.schema === "public" ? this.ident(t.name) : `${this.ident(t.schema)}.${this.ident(t.name)}`;
    }
    private ident(name: string): string {
        return "\"" + name.replace(/"/g, "\"\"") + "\"";
    }
    private lit(s: string): string {
        return "'" + s.replace(/'/g, "''") + "'";
    }
}
